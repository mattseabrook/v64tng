; Embedded DIGPAK table/descriptor/state, literal load-image bytes.
; 07B15 installs CS:0D82 (=load 07DA2) as the built-in command table.
; Entries are command word + CS-relative callback word; FFFF terminates.
; digpak_materialize_driver_descriptor returns CS:0DB8 (=load 07DD8),
; copies up to 78 name bytes to 0DD0, stores capability mask at 0E2E,
; and retains adapter/buffer state in the following region.
